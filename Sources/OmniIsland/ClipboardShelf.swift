import AppKit
import Carbon
import CryptoKit
import UniformTypeIdentifiers

/// One thing that was copied: text, an image, or files.
struct ShelfItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    var id: String
    var kind: Kind
    var text: String?
    /// File name of the saved PNG in the shelf folder.
    var imageFile: String?
    var paths: [String]?
    /// Where it was copied from.
    var sourceApp: String?
    var sourceBundleId: String?
    var date: Date
    /// Content hash, to move a repeated copy to the top instead of adding it twice.
    var digest: String

    /// One-line description for the launcher row.
    var title: String {
        switch kind {
        case .text:
            let line = (text ?? "").split(whereSeparator: \.isNewline).first
                .map { $0.trimmingCharacters(in: .whitespaces) } ?? ""
            return line.count > 120 ? String(line.prefix(119)) + "…" : line
        case .image:
            return "이미지"
        case .files:
            let names = (paths ?? []).map { ($0 as NSString).lastPathComponent }
            guard let first = names.first else { return "파일" }
            return names.count == 1 ? first : "\(first) 외 \(names.count - 1)개"
        }
    }

    /// Text the launcher searches.
    var searchText: String {
        switch kind {
        case .text: return text ?? ""
        case .image: return "이미지 image " + (sourceApp ?? "")
        case .files: return (paths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: " ")
        }
    }
}

/// The clipboard manager's history: keeps what was copied, so it can be
/// pasted again from the launcher ("c " after ⌥H), even after a restart.
@MainActor
final class ClipboardShelf {
    struct Options: Equatable {
        var enabled = true
        var maxItems = 30
        var captureImages = true
        var captureFiles = true
        /// Bundle ids (or app names) whose copies are never kept.
        var ignoreApps: [String] = []
    }

    private(set) var items: [ShelfItem] = []
    var onChange: (() -> Void)?

    private var options = Options()
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    /// Our own writes to the clipboard are not captured again.
    private var ownChangeCount = -1

    static let folder: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? URL(fileURLWithPath: NSHomeDirectory() + "/Library/Application Support")
        return base.appendingPathComponent("OmniIsland/Shelf", isDirectory: true)
    }()

    private static var indexURL: URL { folder.appendingPathComponent("index.json") }

    /// Password managers mark their copies; these are never kept.
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    static let defaultIgnoredApps = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
        "com.apple.keychainaccess", "com.apple.Passwords",
    ]

    init() {
        load()
    }

    func configure(_ options: Options) {
        let wasEnabled = self.options.enabled && timer != nil
        self.options = options
        trim()
        if options.enabled && !wasEnabled {
            lastChangeCount = NSPasteboard.general.changeCount
            timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
        } else if !options.enabled {
            timer?.invalidate()
            timer = nil
        }
    }

    // MARK: - Capturing

    private func poll() {
        let board = NSPasteboard.general
        let count = board.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ownChangeCount else { return }
        capture(board)
    }

    private func capture(_ board: NSPasteboard) {
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.concealedTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        let ignored = Set((Self.defaultIgnoredApps + options.ignoreApps).map { $0.lowercased() })
        if let id = front?.bundleIdentifier?.lowercased(), ignored.contains(id) { return }
        if let name = front?.localizedName?.lowercased(), ignored.contains(name) { return }

        var item = ShelfItem(id: UUID().uuidString, kind: .text, date: Date(), digest: "")
        item.sourceApp = front?.localizedName
        item.sourceBundleId = front?.bundleIdentifier

        if options.captureFiles,
           let urls = board.readObjects(forClasses: [NSURL.self],
                                        options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            item.kind = .files
            item.paths = urls.map(\.path)
            item.digest = Self.digest(Data(item.paths!.joined(separator: "\n").utf8))
        } else if options.captureImages, types.contains(NSPasteboard.PasteboardType.png.rawValue)
                    || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
                  !types.contains(NSPasteboard.PasteboardType.string.rawValue),
                  let png = Self.pngData(board) {
            guard png.count < 25 << 20 else { return }
            item.kind = .image
            item.digest = Self.digest(png)
            if let existing = items.first(where: { $0.digest == item.digest }) {
                return bump(existing)
            }
            let name = item.id + ".png"
            do {
                try FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
                try png.write(to: Self.folder.appendingPathComponent(name), options: .atomic)
            } catch {
                return
            }
            item.imageFile = name
        } else if let text = board.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kept = text.count > 200_000 ? String(text.prefix(200_000)) : text
            item.kind = .text
            item.text = kept
            item.digest = Self.digest(Data(kept.utf8))
        } else {
            return
        }

        if let existing = items.first(where: { $0.digest == item.digest && $0.kind == item.kind }) {
            return bump(existing)
        }
        items.insert(item, at: 0)
        trim()
        save()
        onChange?()
    }

    private func bump(_ item: ShelfItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: index)
        moved.date = Date()
        items.insert(moved, at: 0)
        save()
        onChange?()
    }

    private static func pngData(_ board: NSPasteboard) -> Data? {
        if let png = board.data(forType: .png) { return png }
        guard let tiff = board.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - Taking things out

    /// Puts the item back on the clipboard (and moves it to the top).
    func copy(_ item: ShelfItem) {
        let board = NSPasteboard.general
        board.clearContents()
        switch item.kind {
        case .text:
            board.setString(item.text ?? "", forType: .string)
        case .image:
            if let url = imageURL(item), let data = try? Data(contentsOf: url) {
                board.setData(data, forType: .png)
                if let image = NSImage(data: data), let tiff = image.tiffRepresentation {
                    board.setData(tiff, forType: .tiff)
                }
            }
        case .files:
            let urls = (item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            board.writeObjects(urls)
        }
        ownChangeCount = board.changeCount
        lastChangeCount = board.changeCount
        bump(item)
    }

    /// Several items at once: text joined line by line, anything else as
    /// separate clipboard items.
    func copy(_ items: [ShelfItem]) {
        guard items.count > 1 else {
            if let item = items.first { copy(item) }
            return
        }
        let board = NSPasteboard.general
        board.clearContents()
        if items.allSatisfy({ $0.kind == .text }) {
            board.setString(items.map { $0.text ?? "" }.joined(separator: "\n"), forType: .string)
        } else {
            var objects: [NSPasteboardWriting] = []
            for item in items {
                switch item.kind {
                case .text:
                    objects.append((item.text ?? "") as NSString)
                case .image:
                    if let image = imageURL(item).flatMap({ NSImage(contentsOf: $0) }) { objects.append(image) }
                case .files:
                    objects += (item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
                }
            }
            board.writeObjects(objects)
        }
        ownChangeCount = board.changeCount
        lastChangeCount = board.changeCount
    }

    /// Copies, then presses ⌘V in the app that gets focus back.
    func paste(_ item: ShelfItem) {
        paste([item])
    }

    /// Pastes several items: text in one go, joined line by line; images
    /// and files one after another, since most apps take only the first
    /// thing on the clipboard. `completion` runs once the last ⌘V is sent.
    func paste(_ items: [ShelfItem], completion: (() -> Void)? = nil) {
        guard !items.isEmpty else { completion?(); return }
        // Without the Accessibility permission the ⌘V is silently dropped:
        // leave the item on the clipboard and ask for the permission.
        guard ModifierMonitor.isTrusted(prompt: true) else {
            copy(items)
            completion?()
            return
        }
        let groups: [[ShelfItem]] = items.count == 1 || items.allSatisfy({ $0.kind == .text })
            ? [items] : items.map { [$0] }
        pasteNext(groups[...], completion: completion)
    }

    private func pasteNext(_ groups: ArraySlice<[ShelfItem]>, completion: (() -> Void)?) {
        guard let group = groups.first else { completion?(); return }
        copy(group)
        Self.whenTargetIsReady { [weak self] in
            Self.pressPaste()
            let rest = groups.dropFirst()
            guard !rest.isEmpty else { completion?(); return }
            // Gives the app time to read the clipboard before it changes.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) {
                MainActor.assumeIsolated {
                    guard let self else { completion?(); return }
                    self.pasteNext(rest, completion: completion)
                }
            }
        }
    }

    /// Waits until the launcher has handed the keyboard back to the other
    /// app and the keys that ran the row are let go, so the ⌘V reaches
    /// that app and not the closing launcher. A fixed delay lost the
    /// keystroke whenever the hand-off was slow.
    private static func whenTargetIsReady(_ body: @escaping @MainActor () -> Void) {
        let start = Date()
        let ownPid = ProcessInfo.processInfo.processIdentifier
        func check() {
            let elapsed = Date().timeIntervalSince(start)
            let keyReturned = NSApp.keyWindow == nil
                && NSWorkspace.shared.frontmostApplication?.processIdentifier != ownPid
            let flags = CGEventSource.flagsState(.combinedSessionState)
            let modifiersUp = flags.isDisjoint(with: [.maskAlternate, .maskShift, .maskControl])
            if (elapsed >= 0.08 && keyReturned && modifiersUp) || elapsed >= 1.2 {
                // A little more for the app to make its window key again.
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
                    MainActor.assumeIsolated { body() }
                }
                return
            }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.02) {
                MainActor.assumeIsolated { check() }
            }
        }
        check()
    }

    private static func pressPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        // Keys pressed while the events go out are not held back.
        source?.setLocalEventsFilterDuringSuppressionState(
            [.permitLocalMouseEvents, .permitSystemDefinedEvents],
            state: .eventSuppressionStateSuppressionInterval)
        let vKey = keyCode(for: "v") ?? 9
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        // The left-⌘ device bit too: some apps check it, not just the ⌘ flag.
        let flags = CGEventFlags(rawValue: CGEventFlags.maskCommand.rawValue | 0x8)
        down?.flags = flags
        up?.flags = flags
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// The key that types `character` with ⌘ held on the current layout,
    /// so ⌘V still works on Dvorak or other non-QWERTY layouts.
    private static func keyCode(for character: String) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let pointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(pointer).takeUnretainedValue() as Data
        return data.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            let modifiers = UInt32((cmdKey >> 8) & 0xFF)
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), modifiers,
                                            UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit),
                                            &deadKeys, chars.count, &length, &chars)
                if status == noErr, length > 0,
                   String(utf16CodeUnits: chars, count: length).lowercased() == character {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }

    func remove(_ item: ShelfItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles(of: item)
        save()
        onChange?()
    }

    func clear() {
        items.forEach(deleteFiles)
        items = []
        save()
        onChange?()
    }

    /// For dragging an item out of the launcher.
    func itemProvider(_ item: ShelfItem) -> NSItemProvider {
        switch item.kind {
        case .text:
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .image:
            if let url = imageURL(item), let provider = NSItemProvider(contentsOf: url) { return provider }
            return NSItemProvider()
        case .files:
            guard let first = item.paths?.first else { return NSItemProvider() }
            return NSItemProvider(contentsOf: URL(fileURLWithPath: first)) ?? NSItemProvider()
        }
    }

    func imageURL(_ item: ShelfItem) -> URL? { ShelfThumbnails.imageURL(item) }

    // MARK: - Storage

    private func trim() {
        let limit = max(options.maxItems, 1)
        guard items.count > limit else { return }
        let dropped = items[limit...]
        dropped.forEach(deleteFiles)
        items.removeLast(items.count - limit)
        save()
    }

    private func deleteFiles(of item: ShelfItem) {
        ShelfThumbnails.cache[item.id] = nil
        if let url = imageURL(item) { try? FileManager.default.removeItem(at: url) }
    }

    private func load() {
        guard let data = try? Data(contentsOf: Self.indexURL) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = (try? decoder.decode([ShelfItem].self, from: data)) ?? []
    }

    private func save() {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
        try? data.write(to: Self.indexURL, options: .atomic)
    }
}

/// Small previews for launcher rows: the image itself, or the first file's icon.
@MainActor
enum ShelfThumbnails {
    static var cache: [String: NSImage] = [:]

    static func imageURL(_ item: ShelfItem) -> URL? {
        item.imageFile.map { ClipboardShelf.folder.appendingPathComponent($0) }
    }

    static func image(_ item: ShelfItem) -> NSImage? {
        if let cached = cache[item.id] { return cached }
        var image: NSImage?
        switch item.kind {
        case .image: image = imageURL(item).flatMap { NSImage(contentsOf: $0) }
        case .files: image = item.paths?.first.map { NSWorkspace.shared.icon(forFile: $0) }
        case .text: image = nil
        }
        if let image { cache[item.id] = image }
        return image
    }
}
